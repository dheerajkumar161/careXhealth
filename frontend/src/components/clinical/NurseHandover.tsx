type NurseOption = { id: string; name: string; title?: string | null; load: number };

function NurseSelect({ value, onChange, exclude, placeholder }: { value: string; onChange: (v: string) => void; exclude: (string | null | undefined)[]; placeholder: string }) {
  const { data } = useApi<{ nurses: NurseOption[] }>("/api/nurses");
  const options = (data?.nurses ?? []).filter((n) => !exclude.includes(n.id));
  return (
    <Select value={value} onChange={(e) => onChange(e.target.value)}>
      <option value="">{placeholder}</option>
      {options
        .sort((a, b) => a.load - b.load)
        .map((n) => (
          <option key={n.id} value={n.id}>
            {n.name} — {n.load} patient{n.load === 1 ? "" : "s"}{n.title ? ` · ${n.title}` : ""}
          </option>
        ))}
    </Select>
  );
}

function HandoffPreview({ request }: { request: ReleaseRequest }) {
  const [open, setOpen] = useState(false);
  if (!request.handoff) return null;
  return (
    <>
      <Button size="sm" variant="outline" icon={<ClipboardList className="size-3.5" />} onClick={() => setOpen(true)}>View handoff summary</Button>
      <Modal open={open} onClose={() => setOpen(false)} size="lg" title={request.handoff.title} subtitle={`Generated by the Clinical Intelligence agent${request.handoff.engine ? ` · ${request.handoff.engine === "rules" ? "rule engine" : request.handoff.engine}` : ""}`}>
        <Markdown>{request.handoff.content}</Markdown>
      </Modal>
    </>
  );
}

